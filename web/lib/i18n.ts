export const t = (lang: Lang, key: Key) => dict[lang][key] ?? en[key];

export function tf(
  lang: Lang,
  key: Key,
  params: Record<string, string> = {}
): string {
  return t(lang, key).replace(
    /\{(\w+)\}/g,
    (_match, name: string) => params[name] ?? ""
  );
}